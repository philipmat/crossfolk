import fs from 'node:fs';
import { Worker, isMainThread, parentPort, workerData } from 'node:worker_threads';
if(isMainThread){
 const result={};
 await Promise.all(['space','weather'].map(theme=>new Promise((resolve,reject)=>{
  const worker=new Worker(new URL(import.meta.url),{workerData:theme});
  worker.on('message',data=>{if(data.progress)console.log(data.progress);else{result[theme]=data;resolve();}});worker.on('error',reject);
 })));
 fs.writeFileSync('public/dense-fallbacks.js','// Validated majority-themed grids for bounded-search fallback; generated by scripts/build-fallbacks.mjs.\nexport const denseFallbacks='+JSON.stringify(result)+';\n');
 console.log('Saved',Object.fromEntries(Object.entries(result).map(([k,v])=>[k,v.length])));
}else{
 const{generatePuzzle}=await import('../public/engine.js');const puzzles=[],history=[];
 for(let attempt=0;attempt<16&&puzzles.length<4;attempt++){
  try{const p=generatePuzzle({theme:workerData,size:5,difficulty:'hard',history});puzzles.push(p);history.push(p.entries.map(e=>e.answer));parentPort.postMessage({progress:workerData+' '+puzzles.length+' of 4'});}catch{}
 }
 parentPort.postMessage(puzzles);
}
